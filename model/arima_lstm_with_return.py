def getLSTM(dataset, num_chunk, root_path):
  get_custom_objects().update({'double_tanh':Double_Tanh(double_tanh)})
  model = load_model(opj(root_path, "model", "epoch247.h5"))

  X = np.asarray(dataset).reshape(dataset.shape[0],num_chunk,1)
  pred = model.predict(X)
  return pred

def assemble(pred_arima, pred_lstm):
  pred = np.array(pred_arima) + np.array(pred_lstm) / 2
  pred = pred.squeeze()
  pred = np.maximum(np.minimum(pred, 1), -1)
  return pred

def ARIMA_LSTM(start_date, chunk_size, num_chunk, portfolio, root_path):

  num_asset = len(portfolio)

  data_df, data_ret2 = get_data(start_date, chunk_size, num_chunk, portfolio, root_path)

  nan_values = data_df.isnull().values.any()
  nan_values = data_ret2.isnull().values.any()
  corr_pred_ARIMA, corr_residuals = getArima(data_df)
  ret2_pred_ARIMA, ret2_residuals = getArima(data_ret2)

  corr_pred_LSTM = getLSTM(corr_residuals, num_chunk, root_path)
  ret2_pred_LSTM = getLSTM(ret2_residuals, num_chunk, root_path)

  corr_pred = assemble(corr_pred_ARIMA, corr_pred_LSTM)
  ret2_pred = assemble(ret2_pred_ARIMA, ret2_pred_LSTM)

  cov_mat = np.zeros((num_asset, num_asset), dtype=float)

  # fill with correlation
  start = 0
  for i in range(num_asset):
    end = start + num_asset - i - 1
    cov_mat[i,i+1:] = corr_pred[start:end]
    start = end
    item = portfolio[i]
  cov_mat = cov_mat + cov_mat.T

  # correlation with itself is 1
  np.fill_diagonal(cov_mat, 1)

  # Cov(X,Y) = rho(x,y) * sigma(x) * sigma(y)
  for i in range(num_asset):
    # assume the average of the returns in the short term is 0, then Cov(X,X) = sigma^2(x) = E(x^2)
    cov_mat[:, i] *= np.sqrt(ret2_pred[i])
    cov_mat[i] *= np.sqrt(ret2_pred[i])

  return cov_mat
