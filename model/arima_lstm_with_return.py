"""# Create Residual with ARIMA (for predicting)"""

def rolling_corr(item1, item2, stock_price_df, window=100):
    df_pair = pd.concat([stock_price_df[item1], stock_price_df[item2]], axis=1)
    df_pair.columns = [item1, item2]
    df_corr = df_pair[item1].rolling(window=window).corr(df_pair[item2])
    return df_corr

def get_data(st_date, chunk_size, num_chunk, portfolio, root_path) -> tuple[pd.DataFrame, pd.DataFrame]:
  df = pd.read_csv(opj(root_path, '20industries_ETF_prc_UNSTACKED.csv'))
  pd.to_datetime(df['datadate'], format='%Y-%m-%d')
  df = df.set_index(pd.DatetimeIndex(df['datadate']))

  df = df[df.index >= pd.to_datetime(st_date)]

  num_asset = len(portfolio)

  data_matrix = []
  dict_ret2 = {}
  dict_corr = {}

  for i, asset in tqdm(enumerate(portfolio), total=len(portfolio)):

    # calculate square of the return rate
    ret2_series = df[asset].astype(float).pct_change(chunk_size - 1).shift(-chunk_size+1).fillna(0) ** 2
    ret2_strided = list(ret2_series[[chunk_size*k for k in range(num_chunk)]])
    dict_ret2[str(i)] = ret2_strided

    # calculate history correlation
    for j in range(num_asset-1-i):
      a = portfolio[i]
      b = portfolio[num_asset-1-j]
      corr_series = rolling_corr(a,b, df, chunk_size)[chunk_size - 1:]
      corr_strided = list(corr_series[[chunk_size*k for k in range(num_chunk)]])
      data_matrix.append(corr_strided)

  for i in range(len(data_matrix)):
      dict_corr[str(i)] = data_matrix[i]

  data_corr = pd.DataFrame(dict_corr)
  data_ret2 = pd.DataFrame(dict_ret2)
  data_corr = data_corr.transpose()
  data_ret2 = data_ret2.transpose()
  return data_corr, data_ret2

def getArima(dataset) -> tuple[list, list]:

  orders = [(1,1,0), (0,1,1), (1,1,1), (2,1,1), (2,1,0)]
  models = [ARIMA(order=order, suppress_warnings=False) for order in orders]

  c=0
  residuals = []
  preds = []
  for s in tqdm(np.array(dataset)):
      c+=1
      best_model = auto_arima(s, seasonal=False)

      in_sample_pred = list(best_model.predict_in_sample())
      #pad the first time step of predictions with the average of the prediction values
      #so as to match the length of the s[i] data
      # predictions = [np.mean(predictions)] + predictions

      pred = list(best_model.predict(1))

      res = pd.Series(np.array(s) - np.array(in_sample_pred))
      residuals.append(np.array(res))
      preds.append(pred)

  residuals = pd.DataFrame(residuals)
  return preds, residuals

